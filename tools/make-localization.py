def parse_csharp_strings(path):
    text = path.read_text(encoding="utf-8")
    result = {}
    for key, raw in re.findall(r'\["([^"]+)"\]="((?:\\.|[^"\\])*)",?', text):
        result[key] = json.loads('"' + raw + '"')
    return result

def translated(source, table, *, key=None):
    if key and key in SPELL_TITLES:
        return SPELL_TITLES[key]
    if source in TITLE:
        return TITLE[source]
    if source in LINE:
        return LINE[source]
    raise KeyError(f"Missing translation: {key or ''}: {source}")

def write_table(language, table, values):
    folder = LOC / language
    folder.mkdir(parents=True, exist_ok=True)
    (folder / (table + ".json")).write_text(
        json.dumps(values, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

cards_source = parse_csharp_strings(ROOT / "Scripts" / "CardStrings.g.cs")
powers = {}
cards = {}
for key, value in cards_source.items():
    prefix, entry = key.split(":", 1)
    if prefix == "cards":
        cards[entry] = value
    elif prefix == "powers":
        powers[entry] = value

for language, column in zip(LANGS, range(3)):
    translated_cards = {}
    translated_powers = {}
    for key, value in cards.items():
        if key.endswith(".title"):
            card_id = key[:-6]
            translated_cards[key] = translated(value, TITLE, key=card_id)[column]
        elif key.endswith(".description"):
            translated_cards[key] = "\n".join(translated(line, LINE)[column] for line in value.split("\n"))
        else:
            translated_cards[key] = translated(value, LINE)[column]
    for key, value in powers.items():
        if key.endswith(".title"):
            translated_powers[key] = translated(value, TITLE)[column]
        else:
            translated_powers[key] = "\n".join(translated(line, LINE)[column] for line in value.split("\n"))
    relic_source = parse_csharp_strings(ROOT / "Scripts" / "Relics.cs")
    translated_relics = {}
    for key, value in relic_source.items():
        table_key = key.split(":", 1)[1]
        if key.endswith(".title"):
            translated_relics[table_key] = translated(value, TITLE)[column]
        elif value in RELIC_TEXT:
            translated_relics[table_key] = RELIC_TEXT[value][column]
        else:
            raise KeyError(f"Missing relic translation: {key}: {value}")
    for suffix in ("title", "description", "flavor"):
        value = CHARACTER["THIRD_EYE." + suffix][column]
        translated_relics["THIRD_EYE." + suffix] = value
    translated_character = {
        key: value[column] for key, value in CHARACTER.items() if not key.startswith("THIRD_EYE.")
    }
    translated_cards["SATORI_STRIKE.title"] = CHARACTER["SATORI_STRIKE.title"][column]
    translated_cards["SATORI_STRIKE.description"] = CHARACTER["SATORI_STRIKE.description"][column]
    translated_cards["SATORI_DEFEND.title"] = CHARACTER["SATORI_DEFEND.title"][column]
    translated_cards["SATORI_DEFEND.description"] = CHARACTER["SATORI_DEFEND.description"][column]
    write_table(language, "cards", translated_cards)
    write_table(language, "powers", translated_powers)
    write_table(language, "relics", translated_relics)
    write_table(language, "characters", translated_character)
    write_table(language, "settings_ui", SETTINGS[language])

# The ancient dialogue table is generated in English. Japanese and Korean runs
# use the game's normal English fallback for this story content.
story = json.loads((ROOT / "docs" / "ANCIENT_DIALOGUES_V0314.json").read_text(encoding="utf-8"))["ancients"]
dialogue_maps = {"eng": DIALOGUE_EN, "jpn": DIALOGUE_JA, "kor": DIALOGUE_KO}
for language, translations in dialogue_maps.items():
    ancients = {}
    for ancient, pages in story.items():
        for page_index, page in enumerate(pages):
            for line_index, (speaker, source) in enumerate(page):
                suffix = "r" if page_index >= 2 else ""
                prefix = f"{ancient}.talk.SATORI.{page_index}-{line_index}{suffix}"
                speaker_key = ".char" if speaker == "C" else ".ancient"
                ancients[prefix + speaker_key] = translations[source]
                if line_index < len(page) - 1:
                    ancients[prefix + ".next"] = {"eng": ("Continue" if speaker == "C" else "Reply"),
                                                   "jpn": ("続ける" if speaker == "C" else "返答"),
                                                   "kor": ("계속" if speaker == "C" else "대답")}[language]
    write_table(language, "ancients", ancients)

print(f"Generated cards ({len(translated_cards)}), powers ({len(powers)}), relics ({len(translated_relics)}), characters, settings, and ancient-dialogue tables for {', '.join(LANGS)}.")

